import Foundation
import SQLite3

struct ClipboardRetentionPolicy: Sendable {
    let days: Int
    let textLimit: Int
    let imageLimit: Int

    init(days: Int, textLimit: Int, imageLimit: Int) {
        self.days = min(30, max(1, days))
        self.textLimit = max(0, textLimit)
        self.imageLimit = max(0, imageLimit)
    }
}

enum ClipboardAccess: Sendable {
    case legacy, allowed, requiresUserAction, denied
}

enum ClipboardCapturePolicy {
    static func mayCollect(enabled: Bool, paused: Bool, access: ClipboardAccess) -> Bool {
        enabled && !paused && (access == .legacy || access == .allowed)
    }

    static func shouldIgnore(types: [String], source: String?, excludedApps: Set<String>) -> Bool {
        let sensitive: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        return !sensitive.isDisjoint(with: types) || source.map(excludedApps.contains) == true
    }
}

struct ClipboardEntry: Identifiable, Sendable, Equatable {
    enum Kind: String, Sendable { case text, image }
    let id: Int64
    let kind: Kind
    let text: String?
    let imageFilename: String?
    let source: String?
    let createdAt: Date
}

struct ClipboardStorageError: Error, LocalizedError, Sendable {
    let code: Int32
    let message: String
    var errorDescription: String? { message }
    var isDiskFull: Bool { code == SQLITE_FULL || code == SQLITE_IOERR || code == SQLITE_CANTOPEN }
}

struct ClipboardCleanupReport: Sendable {
    let failedImages: Int
    var warning: String? {
        failedImages > 0 ? "\(failedImages) expired image file(s) could not be removed. Cleanup will retry; metadata retention remains active." : nil
    }
}

private struct ClipboardCleanupError: Error, LocalizedError {
    let count: Int
    var errorDescription: String? { "\(count) image file(s) could not be removed. Cleanup will retry." }
}

struct ClipboardCaptureCancelled: Error {}

/// Invalidate synchronously at the UI boundary, then recheck on the database actor
/// before committing a capture queued by a former collection session.
final class ClipboardCaptureSession: @unchecked Sendable {
    private let lock = NSLock()
    private var revision: UInt64 = 0
    var token: UInt64 { lock.withLock { revision } }
    func invalidate() { lock.withLock { revision &+= 1 } }
    func isCurrent(_ token: UInt64) -> Bool { lock.withLock { revision == token } }
}

private final class ClipboardDatabaseHandle: @unchecked Sendable {
    let pointer: OpaquePointer
    init(_ pointer: OpaquePointer) { self.pointer = pointer }
    deinit { sqlite3_close(pointer) }
}

/// Serial database ownership keeps paging, retention and image files consistent.
actor ClipboardRepository {
    private let handle: ClipboardDatabaseHandle
    private let imagesDirectory: URL
    private let searchIndexed: Bool
    private var db: OpaquePointer { handle.pointer }
    private let transient = unsafeBitCast(-1, to: sqlite3_destructor_type.self)

    init(directory: URL) throws {
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        imagesDirectory = directory.appendingPathComponent("images", isDirectory: true)
        try FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        var pointer: OpaquePointer?
        let code = sqlite3_open_v2(directory.appendingPathComponent("history.sqlite3").path, &pointer, SQLITE_OPEN_CREATE | SQLITE_OPEN_READWRITE | SQLITE_OPEN_FULLMUTEX, nil)
        guard code == SQLITE_OK, let pointer else {
            if let pointer { sqlite3_close(pointer) }
            throw ClipboardStorageError(code: code, message: "Unable to open clipboard history.")
        }
        handle = ClipboardDatabaseHandle(pointer)
        sqlite3_busy_timeout(pointer, 2_000)
        let schema = """
        PRAGMA journal_mode=WAL;
        PRAGMA secure_delete=ON;
        CREATE TABLE IF NOT EXISTS entries (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          kind TEXT NOT NULL,
          text TEXT,
          image_filename TEXT,
          source TEXT,
          created_at REAL NOT NULL
        );
        CREATE INDEX IF NOT EXISTS entries_created_at ON entries(created_at);
        CREATE INDEX IF NOT EXISTS entries_kind_id ON entries(kind,id DESC);
        CREATE TABLE IF NOT EXISTS pending_image_deletions (filename TEXT PRIMARY KEY NOT NULL);
        """
        guard sqlite3_exec(pointer, schema, nil, nil, nil) == SQLITE_OK else {
            throw ClipboardStorageError(code: sqlite3_errcode(pointer), message: String(cString: sqlite3_errmsg(pointer)))
        }
        // Trigram FTS indexes substring searches, including Chinese, without loading
        // historical text into the UI. Older system SQLite builds retain paging and
        // use the LIKE fallback when the optional tokenizer is unavailable.
        let indexSchema = """
        CREATE VIRTUAL TABLE IF NOT EXISTS entries_search USING fts5(text, source, content='entries', content_rowid='id', tokenize='trigram');
        CREATE TRIGGER IF NOT EXISTS entries_search_insert AFTER INSERT ON entries BEGIN
          INSERT INTO entries_search(rowid,text,source) VALUES(new.id,new.text,new.source);
        END;
        CREATE TRIGGER IF NOT EXISTS entries_search_delete AFTER DELETE ON entries BEGIN
          INSERT INTO entries_search(entries_search,rowid,text,source) VALUES('delete',old.id,old.text,old.source);
        END;
        """
        searchIndexed = sqlite3_exec(pointer, indexSchema, nil, nil, nil) == SQLITE_OK
        if searchIndexed {
            var versionStatement: OpaquePointer?
            var version: Int32 = 0
            if sqlite3_prepare_v2(pointer, "PRAGMA user_version", -1, &versionStatement, nil) == SQLITE_OK, let versionStatement {
                if sqlite3_step(versionStatement) == SQLITE_ROW { version = sqlite3_column_int(versionStatement, 0) }
                sqlite3_finalize(versionStatement)
            }
            if version < 1 {
                guard sqlite3_exec(pointer, "INSERT INTO entries_search(entries_search) VALUES('rebuild'); PRAGMA user_version=1;", nil, nil, nil) == SQLITE_OK else {
                    throw ClipboardStorageError(code: sqlite3_errcode(pointer), message: String(cString: sqlite3_errmsg(pointer)))
                }
            }
        }
    }

    @discardableResult func insertText(_ text: String, source: String?, at date: Date = Date(), session: ClipboardCaptureSession? = nil, token: UInt64 = 0) throws -> ClipboardEntry {
        guard session?.isCurrent(token) ?? true else { throw ClipboardCaptureCancelled() }
        return try insert(kind: .text, text: text, imageFilename: nil, source: source, at: date)
    }

    @discardableResult func insertImage(_ data: Data, source: String?, at date: Date = Date(), session: ClipboardCaptureSession? = nil, token: UInt64 = 0) throws -> ClipboardEntry {
        guard session?.isCurrent(token) ?? true else { throw ClipboardCaptureCancelled() }
        let filename = UUID().uuidString + ".png"
        let url = imagesDirectory.appendingPathComponent(filename)
        try data.write(to: url, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        do {
            guard session?.isCurrent(token) ?? true else { throw ClipboardCaptureCancelled() }
            return try insert(kind: .image, text: nil, imageFilename: filename, source: source, at: date)
        }
        catch { try? FileManager.default.removeItem(at: url); throw error }
    }

    func query(search: String, after: Int64?, limit: Int = 30) throws -> [ClipboardEntry] {
        // The primary-key cursor is independent of total history size. The page size
        // controls rendering only; it never limits how many entries are retained.
        var sql = "SELECT id,kind,text,image_filename,source,created_at FROM entries WHERE id < ?"
        let useIndex = searchIndexed && search.count >= 3
        if useIndex { sql += " AND id IN (SELECT rowid FROM entries_search WHERE entries_search MATCH ?)" }
        else if !search.isEmpty { sql += " AND (text LIKE ? ESCAPE '\\' OR source LIKE ? ESCAPE '\\')" }
        sql += " ORDER BY id DESC LIMIT ?"
        let statement = try prepare(sql)
        defer { sqlite3_finalize(statement) }
        sqlite3_bind_int64(statement, 1, after ?? Int64.max)
        var limitIndex: Int32 = 2
        if useIndex {
            bind("\"" + search.replacingOccurrences(of: "\"", with: "\"\"") + "\"", to: 2, in: statement)
            limitIndex = 3
        } else if !search.isEmpty {
            let escaped = search.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "%", with: "\\%").replacingOccurrences(of: "_", with: "\\_")
            bind("%" + escaped + "%", to: 2, in: statement)
            bind("%" + escaped + "%", to: 3, in: statement)
            limitIndex = 4
        }
        sqlite3_bind_int64(statement, limitIndex, Int64(max(1, min(200, limit))))
        return try rows(statement)
    }

    func imageData(for entry: ClipboardEntry) throws -> Data? {
        guard let filename = entry.imageFilename, filename == URL(fileURLWithPath: filename).lastPathComponent else { return nil }
        return try Data(contentsOf: imagesDirectory.appendingPathComponent(filename))
    }

    @discardableResult func purge(policy: ClipboardRetentionPolicy, now: Date = Date()) throws -> ClipboardCleanupReport {
        let cutoff = now.addingTimeInterval(-Double(policy.days) * 86_400).timeIntervalSince1970
        let statement = try prepare("SELECT id,kind,NULL,image_filename,NULL,created_at FROM entries WHERE created_at < ?")
        sqlite3_bind_double(statement, 1, cutoff)
        let expired: [ClipboardEntry]
        do { expired = try rows(statement); sqlite3_finalize(statement) }
        catch { sqlite3_finalize(statement); throw error }
        try remove(entries: expired)
        for (kind, limit) in [(ClipboardEntry.Kind.text, policy.textLimit), (.image, policy.imageLimit)] where limit > 0 {
            let excess = try prepare("SELECT id,kind,NULL,image_filename,NULL,created_at FROM entries WHERE kind = ? ORDER BY id DESC LIMIT -1 OFFSET ?")
            bind(kind.rawValue, to: 1, in: excess)
            sqlite3_bind_int64(excess, 2, Int64(limit))
            let entries: [ClipboardEntry]
            do { entries = try rows(excess); sqlite3_finalize(excess) }
            catch { sqlite3_finalize(excess); throw error }
            try remove(entries: entries)
        }
        return ClipboardCleanupReport(failedImages: try drainImageDeletions())
    }

    func delete(_ entry: ClipboardEntry) throws {
        try remove(entries: [entry])
        let failed = try drainImageDeletions()
        if failed > 0 { throw ClipboardCleanupError(count: failed) }
    }

    func clear() throws {
        try execute("BEGIN IMMEDIATE")
        do {
            try execute("INSERT OR IGNORE INTO pending_image_deletions(filename) SELECT image_filename FROM entries WHERE image_filename IS NOT NULL")
            try execute("DELETE FROM entries")
            try execute("COMMIT")
        } catch { try? execute("ROLLBACK"); throw error }
        _ = try drainImageDeletions()
        var failed = 0
        for url in try FileManager.default.contentsOfDirectory(at: imagesDirectory, includingPropertiesForKeys: nil) {
            do { try FileManager.default.removeItem(at: url) }
            catch { if FileManager.default.fileExists(atPath: url.path) { failed += 1 } }
        }
        try execute("PRAGMA wal_checkpoint(TRUNCATE)")
        if failed > 0 { throw ClipboardCleanupError(count: failed) }
    }

    private func insert(kind: ClipboardEntry.Kind, text: String?, imageFilename: String?, source: String?, at date: Date) throws -> ClipboardEntry {
        let statement = try prepare("INSERT INTO entries(kind,text,image_filename,source,created_at) VALUES(?,?,?,?,?)")
        defer { sqlite3_finalize(statement) }
        bind(kind.rawValue, to: 1, in: statement)
        bind(text, to: 2, in: statement)
        bind(imageFilename, to: 3, in: statement)
        bind(source, to: 4, in: statement)
        sqlite3_bind_double(statement, 5, date.timeIntervalSince1970)
        guard sqlite3_step(statement) == SQLITE_DONE else { throw error() }
        return ClipboardEntry(id: sqlite3_last_insert_rowid(db), kind: kind, text: text, imageFilename: imageFilename, source: source, createdAt: date)
    }

    private func remove(entries: [ClipboardEntry]) throws {
        guard !entries.isEmpty else { return }
        let statement = try prepare("DELETE FROM entries WHERE id = ?")
        defer { sqlite3_finalize(statement) }
        let queue = try prepare("INSERT OR IGNORE INTO pending_image_deletions(filename) VALUES(?)")
        defer { sqlite3_finalize(queue) }
        try execute("BEGIN IMMEDIATE")
        do {
            for entry in entries {
                if let filename = entry.imageFilename {
                    sqlite3_reset(queue)
                    bind(filename, to: 1, in: queue)
                    guard sqlite3_step(queue) == SQLITE_DONE else { throw error() }
                }
                sqlite3_reset(statement)
                sqlite3_bind_int64(statement, 1, entry.id)
                guard sqlite3_step(statement) == SQLITE_DONE else { throw error() }
            }
            try execute("COMMIT")
        } catch { try? execute("ROLLBACK"); throw error }
    }

    /// Queue removal in the same transaction as metadata deletion. A failed unlink
    /// can then be retried after relaunch or the next cleanup without losing its name.
    private func drainImageDeletions() throws -> Int {
        let pending = try prepare("SELECT filename FROM pending_image_deletions")
        var filenames: [String] = []
        while true {
            let code = sqlite3_step(pending)
            if code == SQLITE_DONE { break }
            guard code == SQLITE_ROW else { sqlite3_finalize(pending); throw error() }
            if let filename = column(0, in: pending) { filenames.append(filename) }
        }
        sqlite3_finalize(pending)
        let remove = try prepare("DELETE FROM pending_image_deletions WHERE filename = ?")
        defer { sqlite3_finalize(remove) }
        var failed = 0
        for filename in filenames {
            guard filename == URL(fileURLWithPath: filename).lastPathComponent else { continue }
            let url = imagesDirectory.appendingPathComponent(filename)
            if FileManager.default.fileExists(atPath: url.path) {
                do { try FileManager.default.removeItem(at: url) }
                catch {
                    if FileManager.default.fileExists(atPath: url.path) {
                        failed += 1
                        continue
                    }
                }
            }
            sqlite3_reset(remove)
            bind(filename, to: 1, in: remove)
            guard sqlite3_step(remove) == SQLITE_DONE else { throw error() }
        }
        return failed
    }

    private func rows(_ statement: OpaquePointer) throws -> [ClipboardEntry] {
        var result: [ClipboardEntry] = []
        while true {
            let code = sqlite3_step(statement)
            if code == SQLITE_DONE { return result }
            guard code == SQLITE_ROW else { throw error() }
            guard let kind = column(1, in: statement).flatMap(ClipboardEntry.Kind.init(rawValue:)) else { continue }
            result.append(ClipboardEntry(id: sqlite3_column_int64(statement, 0), kind: kind, text: column(2, in: statement), imageFilename: column(3, in: statement), source: column(4, in: statement), createdAt: Date(timeIntervalSince1970: sqlite3_column_double(statement, 5))))
        }
    }

    private func column(_ index: Int32, in statement: OpaquePointer) -> String? {
        sqlite3_column_text(statement, index).map { String(cString: $0) }
    }
    private func bind(_ value: String?, to index: Int32, in statement: OpaquePointer) {
        if let value { sqlite3_bind_text(statement, index, value, -1, transient) }
        else { sqlite3_bind_null(statement, index) }
    }
    private func prepare(_ sql: String) throws -> OpaquePointer {
        var statement: OpaquePointer?
        guard sqlite3_prepare_v2(db, sql, -1, &statement, nil) == SQLITE_OK, let statement else { throw error() }
        return statement
    }
    private func execute(_ sql: String) throws {
        guard sqlite3_exec(db, sql, nil, nil, nil) == SQLITE_OK else { throw error() }
    }
    private func error() -> ClipboardStorageError {
        ClipboardStorageError(code: sqlite3_errcode(db), message: String(cString: sqlite3_errmsg(db)))
    }
}
