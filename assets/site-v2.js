function setLanguage(language) {
  const selected = Object.hasOwn(translations, language) ? language : "zh";
  const dictionary = translations[selected];
  document.documentElement.lang = selected === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const text = dictionary[element.dataset.i18n];
    if (text !== undefined) element.textContent = text;
  });
  for (const [dataKey, attribute] of [["i18nAlt", "alt"], ["i18nAria", "aria-label"]]) {
    document.querySelectorAll(`[data-${dataKey.replace(/[A-Z]/g, c => "-" + c.toLowerCase())}]`).forEach(element => {
      const text = dictionary[element.dataset[dataKey]];
      if (text !== undefined) element.setAttribute(attribute, text);
    });
  }
  document.querySelectorAll("[data-language]").forEach(button => {
    button.setAttribute("aria-pressed", String(button.dataset.language === selected));
  });
  document.title = dictionary["meta.title"];
  document.querySelector('meta[name="description"]').content = dictionary["meta.description"];
  try { localStorage.setItem("netstats-language", selected); } catch (_) { /* Works with blocked storage. */ }
}
document.querySelectorAll("[data-language]").forEach(button => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});
const tabs = [...document.querySelectorAll('[role="tab"]')];
function activateFeature(tab, focus = false) {
  tabs.forEach(button => {
    const selected = button === tab;
    button.setAttribute("aria-selected", String(selected));
    button.tabIndex = selected ? 0 : -1;
    document.getElementById(button.getAttribute("aria-controls")).hidden = !selected;
  });
  if (focus) tab.focus();
}
tabs.forEach((tab, index) => {
  tab.addEventListener("click", () => activateFeature(tab));
  tab.addEventListener("keydown", event => {
    let next;
    if (event.key === "ArrowRight") next = (index + 1) % tabs.length;
    if (event.key === "ArrowLeft") next = (index + tabs.length - 1) % tabs.length;
    if (event.key === "Home") next = 0;
    if (event.key === "End") next = tabs.length - 1;
    if (next !== undefined) { event.preventDefault(); activateFeature(tabs[next], true); }
  });
});
